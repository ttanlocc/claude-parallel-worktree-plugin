#!/usr/bin/env bash
# dev-stack.sh — run parallel dev stacks ("slots") of the docker-compose stack.
#
# Slot N offsets every host port by N*100 and isolates the stack under its own
# Compose project name, so multiple worktrees/branches can run side by side:
#
#   slot | gateway | frontend | postgres | azurite | project name
#   -----+---------+----------+----------+---------+-------------------
#    0   |  8081   |  5173    |  5432    |  10000  | aiquinta-mfg-s0
#    1   |  8181   |  5273    |  5532    |  10100  | aiquinta-mfg-s1
#    2   |  8281   |  5373    |  5632    |  10200  | aiquinta-mfg-s2
#
# Usage:
#   dev-stack.sh <slot> <up|down|build|logs|ps|config|print-env> [extra compose args...]
#
# Flags:
#   --frontend-only   (up/down only) run just the frontend container on the
#                     slot's frontend port, pointed at the SHARED slot-0
#                     gateway (http://localhost:8081). Cheap mode for UI-only
#                     branches — no per-slot postgres/gateway. NOTE: the
#                     slot-0 gateway must allow this slot's frontend origin
#                     in CORS; see EXTRA_CORS_ORIGINS below.
#
# Environment:
#   EXTRA_CORS_ORIGINS   comma-separated origins appended to the gateway's
#                        CORS_ORIGINS (e.g. when slot-0 serves API calls for
#                        frontend-only slots):
#                        EXTRA_CORS_ORIGINS=http://localhost:5273 dev-stack.sh 0 up
#
# WorkOS caveat: each slot's callback http://localhost:<frontend-port>/auth/callback
# must be registered in the WorkOS dashboard Redirect URIs allow-list (auth has
# no local bypass). See README "Parallel dev stacks".
set -euo pipefail

usage() {
  sed -n '2,30p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
  exit 1
}

REPO_ROOT="$(git rev-parse --show-toplevel)"
COMPOSE_FILE="deploy/docker-compose.yml"

[[ $# -ge 2 ]] || usage

SLOT="$1"
COMMAND="$2"
shift 2

if ! [[ "$SLOT" =~ ^[0-9]$ ]]; then
  echo "error: slot must be an integer 0-9 (got: '$SLOT')" >&2
  exit 1
fi

FRONTEND_ONLY=false
EXTRA_ARGS=()
for arg in "$@"; do
  if [[ "$arg" == "--frontend-only" ]]; then
    FRONTEND_ONLY=true
  else
    EXTRA_ARGS+=("$arg")
  fi
done

case "$COMMAND" in
  up|down|build|logs|ps|config|print-env) ;;
  *)
    echo "error: unknown command '$COMMAND'" >&2
    usage
    ;;
esac

case "$COMMAND" in
  up|down|config|print-env) ;;  # --frontend-only allowed (config/print-env: inspection)
  *)
    if $FRONTEND_ONLY; then
      echo "error: --frontend-only is only valid with 'up' or 'down'" >&2
      exit 1
    fi
    ;;
esac

GATEWAY_HOST_PORT=$((8081 + SLOT * 100))
FRONTEND_HOST_PORT=$((5173 + SLOT * 100))
POSTGRES_HOST_PORT=$((5432 + SLOT * 100))
AZURITE_HOST_PORT=$((10000 + SLOT * 100))
REDIS_HOST_PORT=$((6379 + SLOT * 100))
export GATEWAY_HOST_PORT FRONTEND_HOST_PORT POSTGRES_HOST_PORT AZURITE_HOST_PORT REDIS_HOST_PORT

export COMPOSE_PROJECT_NAME="aiquinta-mfg-s${SLOT}"

# Parse-time interpolated by deploy/docker-compose.yml:
#   GATEWAY_URL   → frontend runtime-config.js (SPA calls the gateway here)
#   CORS_ORIGINS  → gateway allow-list
if $FRONTEND_ONLY; then
  # UI-only mode: this slot runs just the frontend, backed by the shared
  # slot-0 gateway on the default port.
  GATEWAY_URL="http://localhost:8081"
else
  GATEWAY_URL="http://localhost:${GATEWAY_HOST_PORT}"
fi
export GATEWAY_URL

CORS_ORIGINS="http://localhost:${FRONTEND_HOST_PORT},http://localhost:${GATEWAY_HOST_PORT}"
if [[ -n "${EXTRA_CORS_ORIGINS:-}" ]]; then
  CORS_ORIGINS="${CORS_ORIGINS},${EXTRA_CORS_ORIGINS}"
fi
export CORS_ORIGINS

if [[ "$COMMAND" == "print-env" ]]; then
  # Eval-able: eval "$(dev-stack.sh 2 print-env)"
  for var in POSTGRES_HOST_PORT AZURITE_HOST_PORT GATEWAY_HOST_PORT REDIS_HOST_PORT \
             FRONTEND_HOST_PORT COMPOSE_PROJECT_NAME GATEWAY_URL CORS_ORIGINS; do
    printf 'export %s=%q\n' "$var" "${!var}"
  done
  exit 0
fi

cd "$REPO_ROOT"

COMPOSE=(docker compose -f "$COMPOSE_FILE")

# WORKOS_REDIRECT_URI (and the OAuth-connector GATEWAY_WEB_ORIGIN) reach the
# containers via `env_file: ../.env`, which docker compose does NOT interpolate
# — exporting them in this shell has no effect. For non-zero slots we layer a
# generated overlay that pins them to the slot's frontend origin. Slot 0 uses
# the base file alone, keeping today's behavior byte-identical.
# NOTE: matching the Makefile, we pass -f explicitly, which disables compose's
# auto-loading of deploy/docker-compose.override.yml — same as `make dev`.
OVERLAY=""
cleanup() { if [[ -n "$OVERLAY" ]]; then rm -f "$OVERLAY"; fi; }
trap cleanup EXIT

if [[ "$SLOT" != "0" ]]; then
  OVERLAY="$(mktemp "${TMPDIR:-/tmp}/aiquinta-dev-stack-s${SLOT}.XXXXXX.yml")"
  cat > "$OVERLAY" <<EOF
# Generated by dev-stack.sh for slot ${SLOT} — do not edit.
services:
  frontend:
    environment:
      WORKOS_REDIRECT_URI: http://localhost:${FRONTEND_HOST_PORT}/auth/callback
  gateway:
    environment:
      GATEWAY_WEB_ORIGIN: http://localhost:${FRONTEND_HOST_PORT}
EOF
  COMPOSE+=(-f "$OVERLAY")
fi

case "$COMMAND" in
  up)
    if $FRONTEND_ONLY; then
      exec_args=(up --no-deps frontend)
    else
      exec_args=(up)
    fi
    ;;
  down)
    if $FRONTEND_ONLY; then
      # `down` has no per-service form; stop+remove just the frontend so a
      # full stack in the same slot (if any) is left untouched.
      exec_args=(rm --stop --force frontend)
    else
      exec_args=(down)
    fi
    ;;
  build)  exec_args=(build) ;;
  logs)   exec_args=(logs) ;;
  ps)     exec_args=(ps) ;;
  config) exec_args=(config) ;;
esac

echo ">> slot ${SLOT} (${COMPOSE_PROJECT_NAME}): gateway :${GATEWAY_HOST_PORT}  frontend :${FRONTEND_HOST_PORT}  postgres :${POSTGRES_HOST_PORT}  azurite :${AZURITE_HOST_PORT}" >&2
"${COMPOSE[@]}" "${exec_args[@]}" ${EXTRA_ARGS+"${EXTRA_ARGS[@]}"}
